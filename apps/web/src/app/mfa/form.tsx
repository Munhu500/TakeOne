'use client';
import { useEffect, useState } from 'react';
import { supabaseBrowser } from '@/lib/supabase-browser';
import { Button, Input, Skeleton } from '@/components/ui';

type Step = { kind: 'loading' } | { kind: 'enrol'; factorId: string; qr: string; secret: string } | { kind: 'verify'; factorId: string } | { kind: 'error'; text: string };

/** Enrols an authenticator app the first time (QR code and key), then asks for a 6-digit code on every sign-in. */
export function MfaForm() {
  const [step, setStep] = useState<Step>({ kind: 'loading' });
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    void (async () => {
      const mfa = supabaseBrowser().auth.mfa;
      const { data, error: e } = await mfa.listFactors();
      if (e) return setStep({ kind: 'error', text: e.message });
      const verified = data.totp.find((f) => f.status === 'verified');
      if (verified) return setStep({ kind: 'verify', factorId: verified.id });
      // an enrolment that was started but never finished is replaced
      for (const f of data.all.filter((x) => x.factor_type === 'totp' && x.status !== 'verified')) await mfa.unenroll({ factorId: f.id });
      const en = await mfa.enroll({ factorType: 'totp', friendlyName: `TakeOne admin ${new Date().toISOString().slice(0, 10)}` });
      if (en.error || !en.data) return setStep({ kind: 'error', text: en.error?.message ?? 'Two-step sign-in could not be started.' });
      setStep({ kind: 'enrol', factorId: en.data.id, qr: en.data.totp.qr_code, secret: en.data.totp.secret });
    })();
  }, []);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (step.kind !== 'enrol' && step.kind !== 'verify') return;
    setBusy(true); setError(null);
    const { error: err } = await supabaseBrowser().auth.mfa.challengeAndVerify({ factorId: step.factorId, code: code.trim() });
    if (err) { setBusy(false); return setError('That code was not accepted. Check the time on your phone and try the next code.'); }
    window.location.href = '/admin';
  }

  if (step.kind === 'loading') return <div className="mt-8 space-y-3"><Skeleton shape="card" /><Skeleton /></div>;
  if (step.kind === 'error') return <p role="alert" className="mt-6 text-small text-danger-text">{step.text}</p>;
  return (
    <form onSubmit={submit} className="mt-8 space-y-5">
      {step.kind === 'enrol' && (
        <div className="space-y-4">
          <p className="text-small text-secondary">1. Scan this with an authenticator app (1Password, Google Authenticator, Authy).</p>
          {/* the QR is generated by the sign-in service for this account only */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={step.qr} alt="QR code to add TakeOne to your authenticator app" width={176} height={176} className="size-44 rounded-md bg-inverse p-2" />
          <p className="text-small text-secondary">Or enter this key by hand: <code className="break-all text-primary">{step.secret}</code></p>
          <p className="text-small text-secondary">2. Enter the 6-digit code it shows.</p>
        </div>
      )}
      <Input id="mfa-code" label="6-digit code" inputMode="numeric" autoComplete="one-time-code" autoFocus maxLength={6} className="tabular w-40" value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} error={error} />
      <Button type="submit" size="lg" loading={busy} disabled={code.length !== 6} className="w-full">{step.kind === 'enrol' ? 'Turn on two-step sign-in' : 'Continue'}</Button>
    </form>
  );
}
